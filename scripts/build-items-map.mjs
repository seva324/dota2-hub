#!/usr/bin/env node

/**
 * 从 resources/dota-glossary/items.json 生成前端物品映射模块
 * apps/web/src/lib/items-map.ts（id → { key, name }）。
 *
 * key = internal_name 去掉 item_ 前缀，用于拼 steamstatic 物品图 URL
 *   https://cdn.cloudflare.steamstatic.com/apps/dota2/images/dota_react/items/<key>.png
 * name = chinese_name || english_name（match 详情工具提示用）。
 *
 * 用法：node scripts/build-items-map.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const ITEMS_PATH = path.join(ROOT_DIR, 'resources', 'dota-glossary', 'items.json');
const OUTPUT_PATH = path.join(ROOT_DIR, 'apps', 'web', 'src', 'lib', 'items-map.ts');

function main() {
  const items = JSON.parse(fs.readFileSync(ITEMS_PATH, 'utf8'));
  if (!Array.isArray(items)) {
    throw new Error(`${ITEMS_PATH} is not an array`);
  }

  const entries = [];
  for (const item of items) {
    const id = item?.id;
    const internalName = String(item?.internal_name || '');
    if (!Number.isInteger(id) || id <= 0 || !internalName) continue;
    const key = internalName.startsWith('item_') ? internalName.slice(5) : internalName;
    const name = item?.chinese_name || item?.english_name || `Item ${id}`;
    entries.push({ id, key, name });
  }

  entries.sort((a, b) => a.id - b.id);
  const body = entries
    .map((e) => `  ${e.id}: { key: '${e.key}', name: ${JSON.stringify(e.name)} },`)
    .join('\n');

  const source = [
    '// Generated by scripts/build-items-map.mjs — do not edit manually.',
    'export interface ItemMapEntry { key: string; name: string; }',
    `export const itemsById: Record<number, ItemMapEntry> = {\n${body}\n};`,
    '',
  ].join('\n');

  fs.writeFileSync(OUTPUT_PATH, source, 'utf8');
  console.log(`[build-items-map] wrote ${entries.length} items to ${OUTPUT_PATH}`);
}

main();
