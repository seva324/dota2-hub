#!/usr/bin/env node

import fs from 'node:fs/promises';
import fsSync from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const SOURCE_DIR = path.join(ROOT_DIR, 'public', 'images', 'mirror');
const TARGET_DIR = path.join(ROOT_DIR, 'apps', 'web', 'public', 'images', 'mirror');
const GENERATED_MODULE = path.join(ROOT_DIR, 'lib', 'generated', 'asset-mirror-manifest.js');

async function main() {
  await fs.access(SOURCE_DIR);
  await fs.rm(TARGET_DIR, { recursive: true, force: true });
  // Mirror assets must live under apps/web/public so Vite copies them into
  // dist/ for the EdgeOne Pages deploy. Keep the total small: player avatars
  // are compressed webp (see scripts/compress-mirror-players.py).
  await fs.cp(SOURCE_DIR, TARGET_DIR, {
    recursive: true,
    filter: (src) => {
      if (src === SOURCE_DIR) return true;
      const stat = fsSync.statSync(src);
      if (stat.isDirectory()) return true;
      const name = path.basename(src);
      return name === 'manifest.json' || /\.(png|jpe?g|webp|svg|gif|avif)$/i.test(name);
    },
  });
  console.log(`[sync-web-mirror-assets] synced ${SOURCE_DIR} -> ${TARGET_DIR}`);

  // Regenerate the bundled manifest module consumed by lib/asset-mirror.js so
  // serverless functions resolve mirror paths without filesystem access.
  const manifest = JSON.parse(await fs.readFile(path.join(SOURCE_DIR, 'manifest.json'), 'utf8'));
  const moduleSource = `// Generated by scripts/sync-web-mirror-assets.mjs — do not edit manually.\nexport default ${JSON.stringify(manifest)};\n`;
  await fs.mkdir(path.dirname(GENERATED_MODULE), { recursive: true });
  const current = await fs.readFile(GENERATED_MODULE, 'utf8').catch(() => null);
  if (current !== moduleSource) {
    await fs.writeFile(GENERATED_MODULE, moduleSource, 'utf8');
    console.log(`[sync-web-mirror-assets] regenerated ${GENERATED_MODULE}`);
  }

  // Regenerate the mirrored hero id list consumed by apps/web assetUrls so
  // hero images resolve straight to static mirror files instead of the proxy.
  const heroIds = Object.values(manifest.mappings || {})
    .filter((v) => typeof v === 'string' && v.startsWith('/images/mirror/heroes/'))
    .map((v) => Number(v.match(/\/images\/mirror\/heroes\/(\d+)\.png$/)?.[1]))
    .filter((n) => Number.isInteger(n) && n > 0)
    .sort((a, b) => a - b);
  const heroListSource = `// Generated by scripts/sync-web-mirror-assets.mjs — do not edit manually.\nexport const mirroredHeroIds: ReadonlySet<number> = new Set<number>(${JSON.stringify(heroIds)});\n`;
  const heroListPath = path.join(ROOT_DIR, 'apps', 'web', 'src', 'lib', 'mirrored-heroes.ts');
  const currentHeroList = await fs.readFile(heroListPath, 'utf8').catch(() => null);
  if (currentHeroList !== heroListSource) {
    await fs.writeFile(heroListPath, heroListSource, 'utf8');
    console.log(`[sync-web-mirror-assets] regenerated ${heroListPath}`);
  }
}

main().catch((error) => {
  console.error('[sync-web-mirror-assets] failed:', error instanceof Error ? error.message : String(error));
  process.exit(1);
});
